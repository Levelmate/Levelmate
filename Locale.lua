-- Locale.lua
-- Sprachen: Deutsch (Quelltexte) und Englisch. Alle Anzeigetexte laufen ueber
-- Levelmate.L("deutscher Text"). Ist Englisch aktiv, kommt die Uebersetzung aus
-- der Tabelle unten, sonst der deutsche Text unveraendert.
-- Einstellung: Levelmate_DB.language = "auto" (Spielsprache), "de" oder "en".
Levelmate = Levelmate or {}

local EN = {}
Levelmate.LocaleEN = EN

local clientLocale = (GetLocale and GetLocale()) or "enUS"

function Levelmate.Language()
    local l = Levelmate_DB and Levelmate_DB.language
    if l == "de" or l == "en" then return l end
    return (clientLocale == "deDE") and "de" or "en"
end

function Levelmate.L(s)
    if s == nil or Levelmate.Language() ~= "en" then return s end
    return EN[s] or s
end

-- Zusammengesetzte Texte (z. B. Gruende, warum eine Quest uebersprungen wird)
local PATTERNS = {
    { "^schon abgeschlossen$", "already completed" },
    { "^steht schon im Questlog$", "already in your quest log" },
    { "^PvP%-, Fest%- oder Berufsquest$", "PvP, holiday or profession quest" },
    { "^Sonderquest ohne Stufenangabe$", "special quest without level" },
    { "^erst ab Stufe (%d+)$", "only from level %1" },
    { "^Questlevel (%d+) zu hoch %(Todesrisiko%)$", "quest level %1 too high (risk of death)" },
    { "^nur bis Stufe (%d+)$", "only up to level %1" },
    { "^nicht für dein Volk/deine Klasse$", "not for your race/class" },
    { "^wiederholbar/monatlich$", "repeatable/monthly" },
    { "^braucht Berufs%-Spezialisierung$", "needs a profession specialization" },
    { "^braucht Berufsrang$", "needs a profession rank" },
    { "^braucht Beruf$", "needs a profession" },
    { "^braucht Zauber$", "needs a spell" },
    { "^braucht Ruf %(mindestens%)$", "needs reputation (minimum)" },
    { "^braucht Ruf %(höchstens%)$", "needs reputation (maximum)" },
    { "^braucht Gegenstand (%d+) ohne bekannte Quelle$", "needs item %1 with no known source" },
    { "^braucht Gegenstand von (.*) %(Tausch/Beruf/Handel%)$", "needs item from %1 (trade/profession/AH)" },
    { "^Vorquest (.-) fehlt$", "prerequisite quest %1 missing" },
    { "^Gegenstand kommt erst aus Quest (%d+)$", "item only comes from quest %1" },
    { "^schließt sich mit Quest (%d+) aus$", "mutually exclusive with quest %1" },
    { "^Hauptquest (%d+) nicht im Log$", "parent quest %1 not in log" },
    { "^nicht mehr verfügbar$", "no longer available" },
    { "^erst ab Quest (%d+)$", "only after quest %1" },
    { "^gesperrt durch Quest (%d+)$", "blocked by quest %1" },
    { "^Hinführungsquest, Ziel schon erreicht$", "breadcrumb quest, target already reached" },
    { "^von dir übersprungen$", "skipped by you" },
    { "^Dungeonquest %((.*)%)$", "dungeon quest (%1)" },
    { "^Elite%-Gegner %(Gruppe nötig%)$", "elite enemies (group needed)" },
    { "^lohnt sich nicht %(≈(%d+) XP/min, Ø (%d+)%)$", "not worth it (≈%1 XP/min, avg %2)" },
}
function Levelmate.LT(s)
    if type(s) ~= "string" or Levelmate.Language() ~= "en" then return s end
    if EN[s] then return EN[s] end
    for _, p in ipairs(PATTERNS) do
        local out, n = s:gsub(p[1], p[2])
        if n > 0 then return out end
    end
    return s
end

